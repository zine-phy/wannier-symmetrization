#!/usr/bin/env python3
"""Prepare and symmetrize a nonmagnetic HR using an audited basis description."""
import argparse
import hashlib
import itertools
import json
from pathlib import Path
import re
import shutil
import sys
from types import SimpleNamespace

import numpy as np

CORE = Path(__file__).resolve().parent / 'wannsym_core'
sys.path.insert(0, str(CORE))
import wannsym as sw

VERSION = '1.1.0'


def check(ok, message):
    if not ok:
        raise ValueError(message)


def digest(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def write_basis(cfg, out):
    check(cfg.get('magnetic') is False, 'Only confirmed nonmagnetic models are supported')
    check(type(cfg.get('spinor')) is bool, 'spinor must be a JSON boolean')
    check(cfg.get('spin_order') == ('all-up-then-all-down' if cfg['spinor'] else 'scalar'),
          'Unsupported or unverified spin order')
    check(cfg.get('axes_convention') == 'physical-cartesian-columns',
          'Supply audited physical axes, not unchecked projection-file axes')
    evidence = cfg.get('evidence', {})
    for key in ['magnetic_state', 'orbital_order', 'local_axes', 'home_cells', 'spin_order', 'versions']:
        check(isinstance(evidence.get(key), str) and evidence[key].strip(), f'Missing evidence: {key}')
    lattice = np.asarray(cfg['lattice_A'], float)
    check(lattice.shape == (3, 3) and np.isfinite(lattice).all(), 'Invalid lattice')
    atoms, sites = cfg['atoms'], cfg['sites']
    check(len(atoms) > 0 and len(sites) > 0, 'Empty structure/projected basis')
    p = ['# Actual lattice vectors in Angstrom', '# Generated by wannsym skill']
    p += [' '.join(map(str, row)) for row in lattice]
    p += ['# Fractional coordinates, including audited home-cell shifts', '# fx fy fz species', str(len(atoms))]
    for atom in atoms:
        xyz = np.asarray(atom['fractional'], float)
        check(xyz.shape == (3,) and np.isfinite(xyz).all(), 'Invalid fractional site')
        symbol = atom['element']
        check(isinstance(symbol, str) and symbol and len(symbol.split()) == 1, 'Invalid species')
        p.append(' '.join(map(str, xyz)) + ' ' + symbol)
    w = ['# Generated basis; fixed legacy header layout'] * 23 + [str(len(sites)), 'T' if cfg['spinor'] else 'F']
    a = ['# Physical local z and x in global Cartesian coordinates'] * 19 + [str(len(sites))]
    for i, site in enumerate(sites, 1):
        check(type(site['atom']) is int and 1 <= site['atom'] <= len(atoms), 'Invalid 1-based atom index')
        check(isinstance(site['shells'], list) and site['shells'], 'Missing shell list')
        check(all(s in sw.DIMS for s in site['shells']), 'Unsupported shell')
        w.append(f'{i} {site["atom"]} ' + ' '.join(site['shells']))
        axes = np.asarray([site['z'], site['x']], float)
        check(axes.shape == (2, 3) and np.isfinite(axes).all(), 'Invalid axes')
        a.append(str(i) + ' ' + ' '.join(map(str, axes.ravel())))
    for name, lines in [('poscar.in', p), ('wann.in', w), ('locaxis.in', a)]:
        (out / name).write_text('\n'.join(lines) + '\n')
    return sw.read_basis(out)


def apply_ws(h, path):
    """Expand each weighted HR pair once; never attach old wsvec to the output."""
    n = next(iter(h.values())).shape[0]
    result, seen = {}, set()
    with Path(path).open() as f:
        header = f.readline().lower()
        check(re.search(r'\buse_ws_distance\s*[=:]\s*(?:\.true\.|true|t)(?=\s|$)', header),
              'WS file must declare use_ws_distance=true or .true.')
        while True:
            line = f.readline()
            if not line:
                break
            if not line.strip():
                continue
            fields = list(map(int, line.split()))
            check(len(fields) == 5, 'Invalid WS pair record')
            r, i, j = tuple(fields[:3]), fields[3] - 1, fields[4] - 1
            check(r in h and 0 <= i < n and 0 <= j < n and (r, i, j) not in seen, 'Unmatched/duplicate WS pair')
            seen.add((r, i, j))
            nt = int(f.readline()); check(nt > 0, 'Invalid WS multiplicity')
            shifts = set()
            for _ in range(nt):
                t = tuple(map(int, f.readline().split()))
                check(len(t) == 3 and t not in shifts, 'Malformed/duplicate WS translation')
                shifts.add(t)
                rr = tuple(np.asarray(r) + t)
                result.setdefault(rr, np.zeros((n, n), complex))[i, j] += h[r][i, j] / nt
    check(len(seen) == len(h) * n * n, 'Incomplete WS pair list')
    return result


def spectrum(h, k):
    rs, matrices = np.array(list(h)), np.stack(list(h.values()))
    energies, residual = [], 0.
    for start in range(0, len(k), 32):
        hk = np.einsum('kr,rij->kij', np.exp(2j * np.pi * k[start:start+32] @ rs.T), matrices, optimize=True)
        residual = max(residual, float(abs(hk - hk.conj().transpose(0, 2, 1)).max()))
        energies.append(np.linalg.eigvalsh((hk + hk.conj().transpose(0, 2, 1)) / 2))
    return np.concatenate(energies), residual


def band_path(cfg):
    reciprocal = 2 * np.pi * np.linalg.inv(np.asarray(cfg['lattice_A'])).T
    points, distance, parts, ticks, labels = [], [], [], [], []
    offset = 0.
    for segment in cfg.get('band_path', []):
        start, end = np.asarray(segment['start'], float), np.asarray(segment['end'], float)
        check(start.shape == end.shape == (3,) and np.isfinite([start, end]).all(), 'Invalid fractional k path')
        count = segment.get('points', 51)
        check(type(count) is int and count >= 2, 'Each path segment needs at least two points')
        check(len(segment['labels']) == 2, 'Each path segment needs two labels')
        if not ticks:
            ticks.append(offset); labels.append(segment['labels'][0])
        elif labels[-1] != segment['labels'][0]:
            labels[-1] += '|' + segment['labels'][0]
        length = float(np.linalg.norm((end - start) @ reciprocal))
        parts.append([len(points), len(points) + count])
        points.extend(np.linspace(start, end, count))
        distance.extend(offset + np.linspace(0, length, count))
        offset += length; ticks.append(offset); labels.append(segment['labels'][1])
    return np.asarray(points), np.asarray(distance), parts, ticks, labels


def plot_bands(out, x, parts, ticks, labels, before, after, ef, window):
    import matplotlib
    matplotlib.use('Agg')
    from matplotlib import pyplot as plt, font_manager
    from matplotlib.lines import Line2D
    from plot_style import configure_plot_style
    font = configure_plot_style()
    fig, (ax, dd) = plt.subplots(2, 1, figsize=(16, 10), sharex=True, layout='constrained', gridspec_kw={'height_ratios': [3, 1]})
    zero = ef if ef is not None else 0.
    for a, b in parts:
        ax.plot(x[a:b], before[a:b] - zero, color='#1f77b4', lw=1.35)
        ax.plot(x[a:b], after[a:b] - zero, color='#d62728', lw=1.15, ls='--')
        dd.plot(x[a:b], abs(after[a:b] - before[a:b]).max(axis=1), color='black', lw=1.3)
    if window is not None:
        ax.set_ylim(*window)
    if ef is not None:
        ax.axhline(0, color='black', ls=':', lw=1)
    ax.set_ylabel('E - E_F (eV)' if ef is not None else 'Energy (eV)')
    ax.legend(handles=[Line2D([], [], color='#1f77b4', label='Before'), Line2D([], [], color='#d62728', ls='--', label='After')], fontsize=22, ncol=2)
    dd.set_ylabel('max |delta E|\n(eV)', fontsize=22); dd.set_ylim(bottom=0)
    dd.set_xticks(ticks, [s.replace('Gamma', 'Γ') for s in labels]); dd.set_xlabel('Wave-vector path')
    for axis in [ax, dd]:
        axis.set_xlim(x[0], x[-1]); axis.tick_params(direction='in', labelsize=30)
        for t in ticks:
            axis.axvline(t, color='black', lw=.5, alpha=.45)
    for ext in ['png', 'pdf', 'svg']:
        fig.savefig(out / f'bands_before_after.{ext}', dpi=250)
    plt.close(fig)
    return font


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hr', type=Path, required=True)
    parser.add_argument('--case-json', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True, help='New, nonexistent output directory')
    parser.add_argument('--ws-mode', choices=['raw', 'apply'], required=True)
    parser.add_argument('--wsvec', type=Path)
    parser.add_argument('--prepare-only', action='store_true')
    parser.add_argument('--symprec', type=float, default=1e-5)
    parser.add_argument('--validation-tol', type=float, default=1e-7)
    args = parser.parse_args()
    check(args.symprec > 0 and args.validation_tol > 0, 'Invalid tolerances')
    source, out = args.hr.resolve(), args.out.resolve()
    check(not out.exists(), 'Output directory exists; choose a fresh directory')
    check(args.ws_mode != 'apply' or args.wsvec is not None, '--ws-mode apply requires --wsvec')
    check(args.ws_mode != 'raw' or args.wsvec is None, 'Do not supply --wsvec with raw mode')
    cfg = json.loads(args.case_json.read_text())
    check(args.prepare_only or cfg.get('band_path'), 'A verified before/after band_path is required')
    h = sw.read_hr(source); source_hash = digest(source)
    out.mkdir(parents=True)
    basis = write_basis(cfg, out)
    check(next(iter(h.values())).shape == (basis.n, basis.n), 'HR/basis dimensions disagree')
    shutil.copy2(source, out / 'original_hr.dat')
    (out / 'case.json').write_text(json.dumps(cfg, indent=2) + '\n')
    ws_hash = None
    if args.ws_mode == 'apply':
        ws_hash = digest(args.wsvec)
        h = apply_ws(h, args.wsvec)
        shutil.copy2(args.wsvec, out / 'source_wsvec.dat')
        check(digest(out / 'source_wsvec.dat') == ws_hash, 'WS source changed during reading')
    sw.write_hr(out / 'wannier90_hr.dat', h, 'Prepared weighted HR; output degeneracies are one')
    manifest = {'runner_version': VERSION, 'runner_sha256': digest(__file__), 'core': str(CORE / 'wannsym.py'),
                'source_hr': str(source), 'source_hr_sha256': source_hash, 'ws_mode': args.ws_mode,
                'source_wsvec': str(args.wsvec.resolve()) if args.wsvec else None, 'source_wsvec_sha256': ws_hash,
                'config_source': str(args.case_json.resolve()), 'config_sha256': digest(out / 'case.json'),
                'output_interpolation': 'Ordinary HR Fourier sum; never reapply source WS vectors', 'status': 'prepared'}
    check(digest(source) == source_hash == digest(out / 'original_hr.dat'), 'Source HR changed during preparation')
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    if args.prepare_only:
        print(f'PREPARED {out}'); return
    report = sw.run(SimpleNamespace(directory=str(out), input='wannier90_hr.dat', output='wannier90_hr_sym.dat',
                                  symprec=args.symprec, drop_tol=1e-12, validation_tol=args.validation_tol))
    sym = sw.read_hr(out / 'wannier90_hr_sym.dat'); ops = sw.operations(basis, args.symprec)
    internal = sw.reorder(sym, basis.spinor)
    repeated, _ = sw.complete_and_average(sw.prepare(internal, basis), basis, ops)
    zero = np.zeros((basis.n, basis.n), complex)
    repeat = max(float(abs(internal.get(r, zero) - repeated.get(r, zero)).max()) for r in set(internal) | set(repeated))
    check(repeat <= args.validation_tol, f'Repeat projection failed: {repeat}')
    generic = np.vstack([np.array(list(itertools.product([0., .5], repeat=3))), np.random.default_rng(42).random((24, 3))])
    before, bh = spectrum(h, generic); after, ah = spectrum(sym, generic)
    np.savez_compressed(out / 'generic_k_bands.npz', kpoints=generic, before_eV=before, after_eV=after)
    summary = {'before_residuals': sw.residuals(sw.reorder(h, basis.spinor), basis, ops),
               'after_residuals': report['residuals'], 'repeat_projection_max_eV': repeat,
               'generic_band_max_change_eV': float(abs(after - before).max()), 'Bloch_hermiticity_before_after_eV': [bh, ah]}
    check(ah <= args.validation_tol * max(1, len(sym)), 'Output Bloch Hamiltonian is not Hermitian')
    if basis.spinor:
        gap = float(abs(after[:8, 0::2] - after[:8, 1::2]).max())
        summary['eight_TRIM_Kramers_max_eV'] = gap
        check(gap <= args.validation_tol * max(1, basis.n), f'Kramers check failed: {gap}')
    if cfg.get('band_path'):
        k, x, parts, ticks, labels = band_path(cfg)
        before, _ = spectrum(h, k); after, _ = spectrum(sym, k); delta = after - before
        np.savez_compressed(out / 'bands.npz', kpoints=k, distance=x, segments=parts, before_eV=before, after_eV=after, delta_eV=delta)
        summary['path_band_max_change_eV'] = float(abs(delta).max())
        summary['path_band_RMS_change_eV'] = float(np.sqrt(np.mean(delta ** 2)))
        summary['energy_pairing'] = 'Sorted eigenvalues at each k; no eigenvector band tracking'
        summary['plot_font'] = plot_bands(out, x, parts, ticks, labels, before, after, cfg.get('fermi_eV'), cfg.get('plot_window_eV'))
    check(digest(source) == source_hash, 'Original HR changed during execution')
    (out / 'validation.json').write_text(json.dumps(summary, indent=2) + '\n')
    manifest['status'] = 'completed'; manifest['output_hr_sha256'] = digest(out / 'wannier90_hr_sym.dat')
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('COMPLETED', out, json.dumps(summary, indent=2))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, KeyError, IndexError, TypeError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        raise SystemExit(2)
